async function exists(filePath) {
  try {
    await access(filePath, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

async function readTextIfExists(filePath) {
  if (!(await exists(filePath))) {
    return null;
  }
  return readFile(filePath, "utf8");
}

async function readJsonIfExists(filePath) {
  const content = await readTextIfExists(filePath);
  if (content === null) {
    return null;
  }

  try {
    return JSON.parse(content);
  } catch {
    return null;
  }
}

async function detectPackageManager(targetDir, packageJson) {
  const declared = packageJson?.packageManager;
  if (typeof declared === "string") {
    const name = declared.split("@", 1)[0];
    if (["pnpm", "npm", "yarn", "bun"].includes(name)) {
      return name;
    }
  }

  const candidates = [
    ["pnpm-lock.yaml", "pnpm"],
    ["package-lock.json", "npm"],
    ["yarn.lock", "yarn"],
    ["bun.lock", "bun"],
    ["bun.lockb", "bun"],
  ];

  for (const [file, name] of candidates) {
    if (await exists(path.join(targetDir, file))) {
      return name;
    }
  }

  return null;
}

async function detectDirectories(targetDir) {
  const candidates = [
    "src",
    "app",
    "lib",
    "packages",
    "tests",
    "test",
    "docs",
    ".github",
  ];
  const found = [];

  for (const candidate of candidates) {
    if (await exists(path.join(targetDir, candidate))) {
      found.push(candidate);
    }
  }

  return found;
}

async function detectCi(targetDir) {
  const workflows = path.join(targetDir, ".github", "workflows");
  if (!(await exists(workflows))) {
    return [];
  }

  try {
    return (await readdir(workflows))
      .filter((name) => /\.ya?ml$/i.test(name))
      .sort()
      .map((name) => `.github/workflows/${name}`);
  } catch {
    return [];
  }
}

export async function inspectRepository(targetDir) {
  const packageJson = await readJsonIfExists(path.join(targetDir, "package.json"));
  const packageManager = await detectPackageManager(targetDir, packageJson);
  const directories = await detectDirectories(targetDir);
  const ciWorkflows = await detectCi(targetDir);

  return {
    packageJson,
    packageManager,
    directories,
    ciWorkflows,
  };
}

function installCommand(packageManager) {
  switch (packageManager) {
    case "pnpm":
      return "pnpm install";
    case "yarn":
      return "yarn install";
    case "bun":
      return "bun install";
    case "npm":
      return "npm install";
    default:
      return "TODO";
  }
}

function scriptCommand(packageManager, script) {
  if (!script) {
    return "TODO";
  }

  switch (packageManager) {
    case "pnpm":
      return `pnpm ${script}`;
    case "yarn":
      return `yarn ${script}`;
    case "bun":
      return `bun run ${script}`;
    case "npm":
      return `npm run ${script}`;
    default:
      return `TODO: run ${script}`;
  }
}

function commandForScripts(facts, names) {
  const scripts = facts.packageJson?.scripts ?? {};
  const script = names.find((name) => scripts[name]);
  return scriptCommand(facts.packageManager, script);
}

function dependencyList(packageJson) {
  if (!packageJson) {
    return [];
  }

  return [
    ...Object.keys(packageJson.dependencies ?? {}),
    ...Object.keys(packageJson.devDependencies ?? {}),
  ].sort();
}

