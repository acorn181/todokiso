export function renderSource(
  version,
  date = new Date().toISOString().slice(0, 10),
  sourceRevision = null,
) {
  const sourceLine = sourceRevision
    ? `- Source revision: \`${sourceRevision}\`\n`
    : "";

  return `# todokiso source

- Upstream: https://github.com/acorn181/todokiso
- Package revision: todokiso@${version}
${sourceLine}- Bootstrapped: ${date}

## Local adaptations

- Repository-specific commands and policy live in \`../REPOSITORY_PROFILE.md\`.
- If core semantics are adapted locally, document the reason here.

## Upgrade policy

Upgrade todokiso explicitly: compare the current vendored snapshot with a chosen newer release, review semantic changes, update this file, and merge the change through a dedicated process PR.
`;
}

async function plannedFile(targetDir, relativePath, content) {
  const absolutePath = path.join(targetDir, relativePath);
  const existing = await readTextIfExists(absolutePath);

  if (existing === null) {
    return { status: "create", relativePath, absolutePath, content };
  }

  if (existing === content) {
    return { status: "skip", relativePath, absolutePath, content };
  }

  return { status: "conflict", relativePath, absolutePath, content };
}

export async function createBootstrapPlan(
  targetDir,
  {
    assetRoot = PACKAGE_ROOT,
    version = "0.1.0",
    date = new Date().toISOString().slice(0, 10),
    sourceRevision = null,
  } = {},
) {
  const resolvedTarget = path.resolve(targetDir);
  const facts = await inspectRepository(resolvedTarget);
  const entries = [];

  for (const [source, destination] of PORTABLE_FILES) {
    const content = await readFile(path.join(assetRoot, source), "utf8");
    entries.push(await plannedFile(resolvedTarget, destination, content));
  }

  entries.push(
    await plannedFile(
      resolvedTarget,
      "docs/todokiso/SOURCE.md",
      renderSource(version, date, sourceRevision),
    ),
  );
  entries.push(
    await plannedFile(
      resolvedTarget,
      "docs/REPOSITORY_PROFILE.md",
      renderRepositoryProfile(facts),
    ),
  );

  return {
    targetDir: resolvedTarget,
    facts,
    entries,
  };
}

export async function applyBootstrapPlan(plan) {
  const conflicts = plan.entries.filter((entry) => entry.status === "conflict");
  if (conflicts.length > 0) {
    throw new Error(
      `refusing to overwrite existing files: ${conflicts
        .map((entry) => entry.relativePath)
        .join(", ")}`,
    );
  }

  for (const entry of plan.entries) {
    if (entry.status !== "create") {
      continue;
    }

    await mkdir(path.dirname(entry.absolutePath), { recursive: true });
    await writeFile(entry.absolutePath, entry.content, "utf8");
  }
}
